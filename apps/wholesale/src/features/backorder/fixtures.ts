import type { BackorderLine, BackorderSku } from "./types";

/*
 * 미송 목업. API가 붙으면 이 파일만 지운다.
 *
 * `features/product`의 PRODUCTS를 import 하지 않는다 — 미송 행은 주문 시점 스냅샷이라
 * 상품 마스터와 수명이 다르다(다 채워 주면 사라진다). 목업끼리 의존을 만들지 않는다.
 *
 * ⚠️ `Math.random` / `Date.now` / 렌더 시점의 `new Date()`를 쓰지 않는다.
 *    서버 렌더와 클라이언트 렌더가 다른 값을 만들면 하이드레이션이 깨진다.
 *    경과일은 아래 고정 기준일에서 모듈 로드 시 한 번 계산한다.
 */

/**
 * 목업 기준일 = 2024-08-18(UTC).
 * Figma 값에서 역산한 날이다 — `7월 15일 + 34일` = `8월 5일 + 13일` = 8월 18일.
 * "오늘"을 쓰면 화면을 열 때마다 경과일이 달라져 Figma와 대조할 수 없다.
 */
const BASE_DATE = Date.UTC(2024, 7, 18);

const DAY = 86_400_000;

/** `2024.07.15` → UTC ms. 로컬 시간대로 파싱하면 서버(UTC)와 브라우저(KST)의 날짜가 하루 어긋난다 */
function utcOf(date: string): number {
  const [year = 0, month = 1, day = 1] = date.split(".").map(Number);
  return Date.UTC(year, month - 1, day);
}

/**
 * 미송 행 씨앗. 손으로 적는 값이 6개뿐이라 객체보다 튜플이 읽기 쉽다.
 * `[주문번호, 주문일자, 주문시각, 거래처, 미송수량, 주문단가]`
 */
type LineSeed = readonly [
  orderNo: string,
  orderedDate: string,
  orderedTime: string,
  customer: string,
  qty: number,
  unitPrice: number,
];

function toLines(skuId: string, seeds: readonly LineSeed[]): BackorderLine[] {
  return seeds.map(
    ([orderNo, orderedDate, orderedTime, customer, qty, unitPrice]) => ({
      id: `${skuId}-${orderNo}`,
      orderNo,
      orderedDate,
      orderedTime,
      elapsedDays: Math.round((BASE_DATE - utcOf(orderedDate)) / DAY),
      customer,
      qty,
      unitPrice,
    }),
  );
}

