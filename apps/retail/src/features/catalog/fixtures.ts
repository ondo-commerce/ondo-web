/** 도매처 홈이 쓴다. 없는 id로 들어오면 화면이 `notFound()`로 간다 */
export function findWholesaler(id: string): Wholesaler | undefined {
  return WHOLESALERS.find((w) => w.id === id);
}

/** 그 도매처가 마켓에 올린 상품 전부 */
export function productsOfWholesaler(wholesalerId: string): CatalogProduct[] {
  return CATALOG_PRODUCTS.filter((p) => p.wholesalerId === wholesalerId);
}

